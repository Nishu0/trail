const rank: Record<Difficulty, number> = { Easy: 0, Medium: 1, Hard: 2 };
// A short, even practice set: easiest and most-asked first, one pattern at a time.
export function recommendProblems(patterns: Pattern[], count = 12) {
  const chosen = [...new Set(patterns.length ? patterns : CORE_PATTERNS)];
  const queues = chosen.map((pattern) =>
    NEETCODE_150.filter((p) => p.pattern === pattern).sort(
      (a, b) =>
        rank[a.difficulty] - rank[b.difficulty] ||
        Number(b.blind75) - Number(a.blind75),
    ),
  );
  const picked: Problem[] = [];
  for (let i = 0; picked.length < count && queues.some((q) => q[i]); i++)
    for (const queue of queues)
      if (queue[i] && picked.length < count) picked.push(queue[i]);
  return picked;
}
